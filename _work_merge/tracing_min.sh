#!/bin/bash
NEW=/root/kbuild/linux-6.6.73
echo "=== options that select TRACING ==="
grep -n -B6 "select TRACING$" $NEW/kernel/trace/Kconfig | grep -E "^[0-9]+:config|select TRACING" | head -40
echo "=== kernel/trace/Kconfig lines 140-200 ==="
sed -n '140,200p' $NEW/kernel/trace/Kconfig
echo "=== current tracing-ish options enabled ==="
grep -E "^CONFIG_(TRACING|TRACEPOINTS|EVENT_TRACING|RING_BUFFER|FTRACE|FUNCTION_TRACER|DYNAMIC_FTRACE|ENABLE_DEFAULT_TRACERS|FTRACE_SYSCALLS|KPROBES|KPROBE_EVENTS|GENERIC_TRACER|NOP_TRACER|CONTEXT_SWITCH_TRACER|HIST_TRIGGERS|TRACE_EVENT_INJECT|SYNTH_EVENTS|USER_EVENTS|BPF_EVENTS|FUNCTION_GRAPH_TRACER|STACK_TRACER|BLK_DEV_IO_TRACE|TRACER_SNAPSHOT|DYNAMIC_EVENTS|TRACE_CLOCK|BINARY_PRINTF|DEBUG_FS|TRACEFS)=" $NEW/.config | sort
echo DONE
